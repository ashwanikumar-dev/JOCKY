const m5Client = require("../utils/m5Client");

function normalizeFinding(finding) {
  return {
    finding_id: String(finding.finding_id),
    id: String(finding.finding_id),

    evidence_id:
      finding.evidence_id != null ? String(finding.evidence_id) : null,

    rule_id: finding.rule_id,

    severity: String(finding.severity || "").toUpperCase(),

    title: finding.rule_id || "Detection Finding",

    machine: finding.machine_id != null ? String(finding.machine_id) : null,

    reason: finding.reason || "",
    rationale: finding.reason || "",

    timestamp: finding.created_at || null,

    time: finding.created_at
      ? new Date(finding.created_at).toLocaleString("en-GB", {
          day: "2-digit",
          month: "short",
          year: "numeric",
          hour: "2-digit",
          minute: "2-digit",
          hour12: false,
          timeZone: "UTC",
        }) + " UTC"
      : null,
  };
}

module.exports = {
  findAll: async (investigationId) => {
    const endpoint = investigationId
      ? `/findings?investigation_id=${encodeURIComponent(investigationId)}`
      : "/findings";

    console.log("[FINDINGS] investigationId =", investigationId);
    console.log("[FINDINGS] endpoint =", endpoint);

    const findings = await m5Client.get(endpoint);

    console.log("[FINDINGS] M5 response =", findings);

    return Array.isArray(findings) ? findings.map(normalizeFinding) : [];
  },

  findById: async (id) => {
    const findings = await m5Client.get(`/findings/${encodeURIComponent(id)}`);

    return findings ? normalizeFinding(findings) : undefined;
  },

  create: async () => {
    throw new Error(
      "Findings are generated by the M5 detection engine. Product backend cannot create findings directly.",
    );
  },
};
