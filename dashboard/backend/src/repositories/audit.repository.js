const m5Client = require("../utils/m5Client");

function normalizeAuditEntry(entry) {
  return {
    entry_id: String(entry.audit_id ?? entry.entry_id),
    entryId: String(entry.audit_id ?? entry.entry_id),

    investigation_id:
      entry.investigation_id != null ? String(entry.investigation_id) : null,

    action: entry.action || null,

    operator: entry.operator || entry.actor || null,
    actor: entry.actor || entry.operator || null,

    timestamp: entry.timestamp || entry.created_at || null,

    previous_block_hash: entry.previous_block_hash || entry.prev_hash || null,

    prevHash: entry.previous_block_hash || entry.prev_hash || null,

    current_record_hash:
      entry.current_record_hash || entry.current_hash || null,

    currentHash: entry.current_record_hash || entry.current_hash || null,

    verification: entry.verification || entry.status || "VERIFIED",
  };
}

module.exports = {
  findAll: async (investigationId) => {
    const endpoint = investigationId
      ? `/audit?investigation_id=${encodeURIComponent(investigationId)}`
      : "/audit";

    const entries = await m5Client.get(endpoint);

    return Array.isArray(entries) ? entries.map(normalizeAuditEntry) : [];
  },

  create: async () => {
    throw new Error(
      "Audit entries are generated by M5. Product backend cannot create audit entries directly.",
    );
  },
};
