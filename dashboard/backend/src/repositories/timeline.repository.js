const m5Client = require("../utils/m5Client");

function normalizeTimelineEvent(event) {
  const timestamp = event.timestamp_utc || null;

  return {
    id: String(event.timeline_id),
    timeline_id: String(event.timeline_id),

    investigation_id:
      event.investigation_id != null ? String(event.investigation_id) : null,

    evidence_id: event.evidence_id != null ? String(event.evidence_id) : null,

    evidenceRef: event.evidence_id != null ? String(event.evidence_id) : null,

    ts_utc: timestamp,
    timestamp,

    event_type: event.event_type || "EVIDENCE",
    eventType: event.event_type || "EVIDENCE",

    machine_id: event.machine_id != null ? String(event.machine_id) : null,

    sourceNode: event.machine_id != null ? String(event.machine_id) : null,

    description: event.description || `Evidence ${event.evidence_id} verified`,
  };
}

module.exports = {
  findAll: async (investigationId) => {
    const endpoint = investigationId
      ? `/timeline?investigation_id=${encodeURIComponent(investigationId)}`
      : "/timeline";

    const events = await m5Client.get(endpoint);

    return Array.isArray(events) ? events.map(normalizeTimelineEvent) : [];
  },

  create: async () => {
    throw new Error(
      "Timeline events are generated by M5 from verified evidence. Product backend cannot create timeline events directly.",
    );
  },
};
